-- DESIGNING DATABASE FOR EXPENCE TRACKER SYSTEM.

/* ENTITIES.
	1. CUSTOMERS (THIS TABLE WILL STORE CUSTOMERS DETAILS).
    2. CATEGORY (WILL STORE THE EXPENCE CATEGORY).
    3. EXPENCES (IN THIS TABLE WE ARE GOING TO STORE EXPENCES OF ALL THE USERS).
*/

-- CREATING DATABASE.
CREATE DATABASE TRACK_EXPENCE;
USE TRACK_EXPENCE;

-- CUSTOMER TABLE.
CREATE TABLE customers(
	customer_id INT PRIMARY KEY,
    first_name VARCHAR(20),
    last_name varchar(20),
    mobile_number VARCHAR(10) NOT NULL,
    email VARCHAR(50) NOT NULL
);


-- CATEGORY TABLE.
CREATE TABLE category(
	cate_id INT PRIMARY KEY,
    cate_name VARCHAR(40) NOT NULL UNIQUE
);


-- EXPENCE TABLE.
CREATE TABLE EXPENCE(
	exp_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    cate_id INT NOT NULL,
    time_stamp DATETIME,
    FOREIGN KEY (customer_id)
		REFERENCES customers(customer_id),
	FOREIGN KEY (cate_id)
		REFERENCES category(cate_id)
);